#!/usr/bin/env python3
"""
bake_tables.py - turn the MAME 'tithermos' ROM + PLA files into a C header.

The TMS0970 core only needs four tiny truth tables (instruction, microinstruction,
output and segment PLAs) plus the 1 KB program ROM.  MAME evaluates the PLAs at
runtime from Berkeley-format text files; we evaluate them once here, using the same
rules as MAME's plaparse.cpp / pla.cpp, and emit plain arrays.

Usage:
  python3 bake_tables.py tmc0910b \
      tms0970_common2_instr.pla tms0970_tithermos_micro.pla \
      tms0980_tithermos_output.pla tms0980_common2_segment.pla \
      -o tithermos_tables.h
"""
import argparse, sys

# (inputs, outputs, terms) exactly as configured in MAME's tms0970.cpp
IPLA = (8, 15, 18)
MPLA = (5, 15, 32)
OPLA = (4, 8, 16)
SPLA = (3, 8, 8)


def parse_pla(path, n_in, n_out, n_terms):
    """Parse a Berkeley/espresso PLA file the way MAME does and return a list of
    truth-table values, one per input combination."""
    declared_i = declared_o = None
    phase = None
    terms = []
    with open(path, "r", errors="replace") as f:
        for raw in f:
            line = raw.split("#", 1)[0].strip()   # MAME stops at '#', also mid-line
            if not line:
                continue
            if line.startswith("."):
                parts = line.split()
                kw = parts[0][1:].lower()
                if kw == "i":
                    declared_i = int(parts[1])
                elif kw == "o":
                    declared_o = int(parts[1])
                elif kw == "phase":
                    phase = [c for c in "".join(parts[1:]) if c in "01"]
                continue
            parts = line.split()
            in_pat = [c for c in parts[0] if c in "01-~"]
            out_pat = [c for c in "".join(parts[1:]) if c in "01-~"]
            if len(in_pat) != n_in or len(out_pat) != n_out:
                raise ValueError(
                    f"{path}: term has {len(in_pat)} inputs/{len(out_pat)} outputs, "
                    f"expected {n_in}/{n_out}: {line!r}")
            terms.append((in_pat, out_pat))
    if declared_i not in (None, n_in) or declared_o not in (None, n_out):
        raise ValueError(f"{path}: header says .i {declared_i} .o {declared_o}, "
                         f"expected {n_in}/{n_out}")
    if len(terms) != n_terms:
        print(f"note: {path} has {len(terms)} terms, MAME is configured for {n_terms}",
              file=sys.stderr)
    terms = terms[:n_terms]          # MAME ignores extra terms

    # output polarity: .phase char '0' => that output is inverted
    xor_mask = 0
    if phase:
        for i, c in enumerate(phase[:n_out]):
            if c == "0":
                xor_mask |= 1 << i

    table = []
    for v in range(1 << n_in):
        out = 0
        for in_pat, out_pat in terms:
            ok = True
            for i, c in enumerate(in_pat):       # first character = input bit 0
                bit = (v >> i) & 1
                if c == "1" and not bit:
                    ok = False
                elif c == "0" and bit:
                    ok = False
                elif c == "~":                   # inhibited term, never matches
                    ok = False
                if not ok:
                    break
            if ok:
                for i, c in enumerate(out_pat):  # first character = output bit 0
                    if c == "1":
                        out |= 1 << i
        table.append(out ^ xor_mask)
    return table


def emit_array(f, ctype, name, values, width):
    f.write(f"static const {ctype} {name}[{len(values)}] = {{\n")
    for i in range(0, len(values), 8):
        row = ", ".join(f"0x{v:0{width}X}" for v in values[i:i + 8])
        f.write(f"  {row},\n")
    f.write("};\n\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rom")
    ap.add_argument("ipla")
    ap.add_argument("mpla")
    ap.add_argument("opla")
    ap.add_argument("spla")
    ap.add_argument("-o", "--out", default="tithermos_tables.h")
    a = ap.parse_args()

    rom = open(a.rom, "rb").read()
    if len(rom) != 1024:
        sys.exit(f"ROM must be 1024 bytes, got {len(rom)}")

    ipla = parse_pla(a.ipla, *IPLA)
    mpla = parse_pla(a.mpla, *MPLA)
    opla = parse_pla(a.opla, *OPLA)
    spla = parse_pla(a.spla, *SPLA)

    with open(a.out, "w") as f:
        f.write("// Generated by bake_tables.py - do not edit.\n")
        f.write("// TI Electronic Digital Thermostat (TMS0970 / TMC0910B).\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        emit_array(f, "uint8_t", "kRom", list(rom), 2)
        emit_array(f, "uint16_t", "kIpla", ipla, 4)
        emit_array(f, "uint16_t", "kMpla", mpla, 4)
        emit_array(f, "uint8_t", "kOpla", opla, 2)
        emit_array(f, "uint8_t", "kSpla", spla, 2)
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
